package at.minecraftschurli.mods.dynassetgen.test;

import at.minecraftschurli.mods.dynassetgen.api.DynamicPack;
import at.minecraftschurli.mods.dynassetgen.api.DynamicPacks;
import at.minecraftschurli.mods.dynassetgen.api.GenerationContext;
import at.minecraftschurli.mods.dynassetgen.api.ResourceGenerator;
import at.minecraftschurli.mods.dynassetgen.api.ResourceOutput;
import com.google.gson.JsonParser;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.concurrent.atomic.AtomicReference;
import net.minecraft.advancements.Advancement;
import net.minecraft.advancements.AdvancementType;
import net.minecraft.advancements.criterion.InventoryChangeTrigger;
import net.minecraft.core.registries.Registries;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.crafting.Recipe;
import net.minecraft.world.level.storage.loot.LootPool;
import net.minecraft.world.level.storage.loot.LootTable;
import net.minecraft.world.level.storage.loot.entries.LootItem;
import net.minecraft.world.level.storage.loot.parameters.LootContextParamSets;
import net.minecraft.world.level.storage.loot.providers.number.ConstantValue;
import org.jspecify.annotations.Nullable;

/// The packs registered by the test mod.
// The pack fields are set by register(), which runs during mod construction, before any test reads them.
@SuppressWarnings("NotNullFieldNotInitialized")
public final class TestPacks {
    /// Namespace of the test packs. 
    public static final String NAMESPACE = "dynassetgen_test";
    /// Namespace of the scale packs. 
    public static final String SCALE_NAMESPACE = "dynassetgen_scale";
    /// Id of the single generator of the scale packs. Names its cache blob. 
    public static final String SCALE_GENERATOR = "scale_gen";
    /// Number of files generated by each scale pack. 
    public static final int SCALE_FILES = 15_000;
    /// Version of the cache key of the scale pack. 
    public static final int SCALE_VERSION = 1;
    /// Content of every scale file. 
    private static final byte[] SCALE_CONTENT = bytes("{\"values\":[\"minecraft:stick\"]}");

    /// Location of the file of the cache test packs. 
    public static final String CACHE_FILE = "cache/value.json";
    /// Location of the extra file, emitted only while the value is `v1`. 
    public static final String EXTRA_FILE = "cache/extra.json";
    /// Id of the generator of every cache test pack. Names its cache blob. 
    public static final String CACHE_GENERATOR = "gen";

    /// Data pack with a recipe, a tag, a loot table, an advancement and a raw JSON file. 
    public static DynamicPack data;
    /// Data pack that is disabled because a mod is missing. 
    public static DynamicPack disabled;
    /// Data pack with [#SCALE_FILES] generated files, served from the cache. 
    public static DynamicPack scale;
    /// Data pack with the same generated files as [#scale], but without a cache key. 
    public static DynamicPack scaleUncached;
    /// Asset pack with a lang file. 
    public static DynamicPack assets;
    /// Cache test pack: keyed by its value, read twice from memory. 
    public static DynamicPack memoryHit;
    /// Cache test pack: keyed by its value, served from its disk blob after the memory is cleared. 
    public static DynamicPack diskHit;
    /// Cache test pack: keyed by its value, whose value and emitted files change between reads. 
    public static DynamicPack keyChange;
    /// Cache test pack: keyed by a key class without `toString()`, so it has no disk blob. 
    public static DynamicPack noToStringKey;

    /// State of the generator of [#memoryHit]. 
    public static final Probe MEMORY_PROBE = new Probe();
    /// State of the generator of [#diskHit]. 
    public static final Probe DISK_PROBE = new Probe();
    /// State of the generator of [#keyChange]. 
    public static final Probe KEY_CHANGE_PROBE = new Probe();
    /// State of the generator of [#noToStringKey]. 
    public static final Probe PLAIN_PROBE = new Probe();
    /// Number of times the scale generator ran, keyed or not. 
    public static final AtomicInteger SCALE_GENERATIONS = new AtomicInteger();
    /// The key of [#noToStringKey]. Its identity is its equality. 
    public static final PlainKey PLAIN_KEY = new PlainKey();

    private TestPacks() {}

    /// Mutable state that the cache test generators read at generate time. 
    public static final class Probe {
        /// Number of times a generator of this probe ran. 
        public final AtomicInteger generations = new AtomicInteger();
        /// Value written into the file and used in its cache key. 
        public final AtomicReference<String> value = new AtomicReference<>("v1");
    }

    /// Cache key hashed by its `toString()`. 
    public record TestKey(String value) {}

    /// Cache key of the scale pack. 
    public record ScaleKey(int version) {}

    /// Cache key whose class does not override `toString()`, so its generator has no disk blob. 
    public static final class PlainKey {}

    /// Generator of the cache test packs. Its key is a [TestKey] of the probe value, or [#PLAIN_KEY] if
    /// `plainKey` is set. It writes [#CACHE_FILE] with the value, and [#EXTRA_FILE] while the value
    /// is `v1`.
    ///
    /// @param probe    the state of the generator
    /// @param plainKey whether the key is [#PLAIN_KEY]
    public record ProbeGenerator(Probe probe, boolean plainKey) implements ResourceGenerator {
        @Override
        public Object createCacheKey(GenerationContext ctx) {
            return plainKey ? PLAIN_KEY : new TestKey(probe.value.get());
        }

        @Override
        public void generate(GenerationContext ctx, ResourceOutput output) {
            probe.generations.incrementAndGet();
            String value = probe.value.get();
            output.accept(id(NAMESPACE, CACHE_FILE), () -> bytes("{\"value\":\"" + value + "\"}"));
            if ("v1".equals(value)) {
                output.accept(id(NAMESPACE, EXTRA_FILE), () -> bytes("{\"extra\":true}"));
            }
        }
    }

    /// Generator of the scale packs. It writes [#SCALE_FILES] small files, and has a [ScaleKey] if
    /// `keyed` is set.
    ///
    /// @param keyed whether the generator has a cache key
    public record ScaleGenerator(boolean keyed) implements ResourceGenerator {
        @Override
        public @Nullable Object createCacheKey(GenerationContext ctx) {
            return keyed ? new ScaleKey(SCALE_VERSION) : null;
        }

        @Override
        public void generate(GenerationContext ctx, ResourceOutput output) {
            SCALE_GENERATIONS.incrementAndGet();
            for (int i = 0; i < SCALE_FILES; i++) {
                output.accept(scaleFile(i), () -> SCALE_CONTENT);
            }
        }
    }

    /// Creates all test packs with the given registrar. Must be called during mod construction.
    ///
    /// @param packs the registrar of the test mod
    public static void register(DynamicPacks packs) {
        data = packs.data(id(NAMESPACE, "data"));
        data.addJson(id(NAMESPACE, "recipe/dirt_to_diamond.json"), _ -> JsonParser.parseString("""
            {
              "type": "minecraft:crafting_shaped",
              "category": "misc",
              "pattern": ["###", "###", "###"],
              "key": {"#": "minecraft:dirt"},
              "result": {"id": "minecraft:diamond", "count": 1}
            }
            """));
        data.addJson(id(NAMESPACE, "recipe/json_stick.json"), _ -> JsonParser.parseString("""
            {
              "type": "minecraft:crafting_shapeless",
              "ingredients": ["minecraft:dirt", "minecraft:dirt"],
              "result": {"id": "minecraft:stick", "count": 2}
            }
            """));
        data.addJson(id(NAMESPACE, "tags/item/generated.json"), _ -> JsonParser.parseString("""
            {"values": ["minecraft:stick"]}
            """));
        data.addCodec(id(NAMESPACE, "loot_table/blocks/generated.json"), LootTable.DIRECT_CODEC,
            _ -> LootTable.lootTable()
                .setParamSet(LootContextParamSets.BLOCK)
                .withPool(LootPool.lootPool()
                    .setRolls(ConstantValue.exactly(1.0F))
                    .add(LootItem.lootTableItem(Items.DIRT)))
                .build());
        data.addCodec(id(NAMESPACE, "advancement/progress/generated.json"), Advancement.CODEC,
            _ -> Advancement.Builder.advancement()
                .display(Items.DIRT, Component.literal("Generated"), Component.literal("Generated by DynAssetGen"),
                    null, AdvancementType.TASK, true, true, false)
                .addCriterion("has_dirt", InventoryChangeTrigger.TriggerInstance.hasItems(Items.DIRT))
                .build(id(NAMESPACE, "progress/generated")).value());

        disabled = packs.data(id(NAMESPACE, "disabled")).onlyIfModsLoaded("definitely_not_a_mod");
        disabled.addJson(id(NAMESPACE, "recipe/disabled_recipe.json"), _ -> JsonParser.parseString("""
            {
              "type": "minecraft:crafting_shaped",
              "category": "misc",
              "pattern": ["#"],
              "key": {"#": "minecraft:dirt"},
              "result": {"id": "minecraft:stick", "count": 1}
            }
            """));

        scale = packs.data(id(SCALE_NAMESPACE, "scale"));
        scale.add(id(SCALE_NAMESPACE, SCALE_GENERATOR), new ScaleGenerator(true));
        scaleUncached = packs.data(id(SCALE_NAMESPACE, "scale_uncached"));
        scaleUncached.add(id(SCALE_NAMESPACE, SCALE_GENERATOR), new ScaleGenerator(false));

        memoryHit = packs.data(id(NAMESPACE, "memory_hit"));
        memoryHit.add(id(NAMESPACE, CACHE_GENERATOR), new ProbeGenerator(MEMORY_PROBE, false));
        diskHit = packs.data(id(NAMESPACE, "disk_hit"));
        diskHit.add(id(NAMESPACE, CACHE_GENERATOR), new ProbeGenerator(DISK_PROBE, false));
        keyChange = packs.data(id(NAMESPACE, "key_change"));
        keyChange.add(id(NAMESPACE, CACHE_GENERATOR), new ProbeGenerator(KEY_CHANGE_PROBE, false));
        noToStringKey = packs.data(id(NAMESPACE, "no_tostring_key"));
        noToStringKey.add(id(NAMESPACE, CACHE_GENERATOR), new ProbeGenerator(PLAIN_PROBE, true));

        assets = packs.assets(id(NAMESPACE, "assets"));
        assets.addJson(id(NAMESPACE, "lang/en_us.json"), _ -> JsonParser.parseString("""
            {"%s.lang.hello": "Hello from DynAssetGen"}
            """.formatted(NAMESPACE)));
    }

    /// Returns the path of one file of the scale packs.
    ///
    /// @param index the file index, below [#SCALE_FILES]
    /// @return the pack-relative path
    public static Identifier scaleFile(int index) {
        return id(SCALE_NAMESPACE, String.format("tags/item/gen/%05d.json", index));
    }

    /// Returns an identifier in the given namespace.
    ///
    /// @param namespace the namespace
    /// @param path      the path
    /// @return the identifier
    public static Identifier id(String namespace, String path) {
        return Identifier.fromNamespaceAndPath(namespace, path);
    }

    /// Returns the key of a recipe of the `data` pack.
    ///
    /// @param name the recipe name
    /// @return the recipe key
    public static ResourceKey<Recipe<?>> recipeKey(String name) {
        return ResourceKey.create(Registries.RECIPE, id(NAMESPACE, name));
    }

    private static byte[] bytes(String text) {
        return text.getBytes(StandardCharsets.UTF_8);
    }
}
